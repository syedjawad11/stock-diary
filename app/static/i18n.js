function t(lang, key, vars) {
  const dict = STRINGS[lang] || STRINGS.en;
  let s = dict[key];
  if (s === undefined) s = STRINGS.en[key] !== undefined ? STRINGS.en[key] : key;
  if (vars) {
    Object.keys(vars).forEach(function (k) {
      s = s.split("{" + k + "}").join(String(vars[k]));
    });
  }
  return s;
}
